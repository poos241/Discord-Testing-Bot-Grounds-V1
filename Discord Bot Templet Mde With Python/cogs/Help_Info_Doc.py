def _help_command_key(cmd):
    """The gate-table key for one live command object.

    Qualified names use underscores ("voicexp config" -> "voicexp_config",
    "ticket open" -> "ticket_open"); the Check Introduction user context
    menu maps to its grantable key "intro_check_ctx".
    """
    if isinstance(cmd, discord.UserCommand):
        if cmd.name == "Check Introduction":
            return "intro_check_ctx"
        return cmd.name.replace(" ", "_")
    qn = getattr(cmd, "qualified_name", None) or getattr(cmd, "name", "")
    return qn.replace(" ", "_")


class _HelpVisibility:
    """One /help invocation's permission snapshot.

    Loads the guild's custom grants ONCE (get_all_command_permissions)
    and evaluates, in memory, whether a member may use each command.
    The precedence mirrors utils.permissions.custom_perm_decision (the
    source of truth) plus has_command_permission's Administrator
    bypass. Read-only: never sends anything (unlike
    check_slash_permission, which answers with a denial -- that is why
    the filter must not call it once per listed command).
    """

    def __init__(self, guild, member):
        self.guild = guild
        self.member = member
        self._grants_by_command = None
        self._appeal_cfg = None
        self._appeal_cfg_loaded = False
        self._role_ids = (
            {str(r.id) for r in (getattr(member, "roles", None) or [])}
            if member is not None else set()
        )

    async def load(self):
        """Load the guild's custom grants once. On any failure (DB not
        connected, table missing) fall back to defaults-only and warn --
        /help still works, it just cannot see custom grants."""
        if self.guild is None or self._grants_by_command is not None:
            return
        try:
            rows = await get_all_command_permissions(str(self.guild.id))
        except Exception as exc:  # noqa: BLE001
            print(f"[HELP] grants load failed, using defaults only: {exc!r}")
            rows = []
        by_cmd = {}
        for row in rows or []:
            by_cmd.setdefault(row.get("command"), []).append(row)
        self._grants_by_command = by_cmd

    def _default_allowed(self, marker):
        """The command's normal Discord check, from its table marker."""
        if marker == "open":
            return True
        perms = getattr(self.member, "guild_permissions", None) if self.member is not None else None
        if perms is None:
            return False
        if marker == "admin":
            return bool(perms.administrator)
        if marker == "manage_guild":
            return bool(perms.manage_guild or perms.administrator)
        if marker == "manage_msgs":
            return bool(perms.manage_messages or perms.administrator)
        if marker == "manage_channels":
            return bool(perms.manage_channels or perms.administrator)
        return False  # unknown marker: fail closed

    async def _appeal_staff_allowed(self):
        """The appeal_list / appeal_review default: the configured staff
        role, or Manage Messages / Administrator when no staff role is
        set (cogs/Appeals.py is_appeal_staff). The staff config is
        loaded once per invocation and cached here."""
        if not self._appeal_cfg_loaded:
            try:
                self._appeal_cfg = (
                    await get_appeal_guild_config(str(self.guild.id))
                    if self.guild is not None else {}
                )
            except Exception as exc:  # noqa: BLE001
                print(f"[HELP] appeal config load failed: {exc!r}")
                self._appeal_cfg = {}
            self._appeal_cfg_loaded = True
        cfg = self._appeal_cfg or {}
        perms = getattr(self.member, "guild_permissions", None) if self.member is not None else None
        if perms is not None and getattr(perms, "administrator", False):
            return True
        staff_role_id = cfg.get("staff_role_id")
        if staff_role_id:
            return any(str(r) == str(staff_role_id) for r in self._role_ids)
        return bool(perms.manage_messages or perms.administrator) if perms is not None else False

    async def can_use(self, key):
        """May this member use the command with this gate-table key?"""
        marker = _HELP_DEFAULT_CHECKS.get(key)
        if marker is None:
            return False  # unlisted command: hidden (fail-closed)
        member = self.member
        if member is None:
            return marker == "open"
        if marker == "owner":
            # Owner-only commands never go through check_slash_permission,
            # so the Administrator bypass does not apply to them.
            return member.id in OWNER_IDS
        perms = getattr(member, "guild_permissions", None)
        if perms is not None and getattr(perms, "administrator", False):
            return True
        grants = (self._grants_by_command or {}).get(key) or []
        if not grants:
            if marker == "appeal_staff":
                return await self._appeal_staff_allowed()
            return self._default_allowed(marker)
        user_id = str(member.id)
        # (1) user DENY, (2) user ALLOW, (3) role DENY, (4) role ALLOW --
        # same order as custom_perm_decision; admin was checked above.
        for grant in grants:
            if (grant.get("target_type") == "user"
                    and str(grant.get("target_id")) == user_id
                    and not grant.get("allowed")):
                return False
        for grant in grants:
            if (grant.get("target_type") == "user"
                    and str(grant.get("target_id")) == user_id
                    and grant.get("allowed")):
                return True
        for grant in grants:
            if (grant.get("target_type") == "role"
                    and str(grant.get("target_id")) in self._role_ids
                    and not grant.get("allowed")):
                return False
        for grant in grants:
            if (grant.get("target_type") == "role"
                    and str(grant.get("target_id")) in self._role_ids
                    and grant.get("allowed")):
                return True
        return False  # custom rules exist but nothing matches -> deny


async def _visible_tag_names(guild, member):
    """Tag names with at least one command this user may use.

    Callers building a TagPageView should pass this list (instead of
    list(COMMAND_TAGS)) so empty tags never appear as dropdown options
    -- Discord rejects a select with zero options, and an empty tag
    could only ever answer "nothing you can use".
    """
    vis = _HelpVisibility(guild, member)
    await vis.load()
    names = []
    for tag, entries in COMMAND_TAGS.items():
        for entry in entries:
            if await vis.can_use(entry.replace(" ", "_")):
                names.append(tag)
                break
    return names


# Autocomplete helper
async def autocomplete_query(ctx: discord.AutocompleteContext):
    val = ctx.value.lower()
    # Visibility: suggestions only ever name things this user may use.
    # The grants snapshot is one DB read per keystroke; the per-command
    # evaluation after that is in-memory.
    interaction = getattr(ctx, "interaction", None)
    vis = _HelpVisibility(
        getattr(interaction, "guild", None) if interaction else None,
        getattr(interaction, "user", None) if interaction else None,
    )
    await vis.load()
    # Categories: only those with at least one visible command.
    categories = set()
    for cog in ctx.bot.cogs.values():
        cat = getattr(cog.__class__, "HelpCategory", None)
        if cat:
            categories.add(cat)
    visible_categories = set()
    for cmd in _iter_runnable_commands(ctx.bot.application_commands):
        inst = _cmd_cog(cmd)
        cat = getattr(inst, "HelpCategory", None)
        cog_name = inst.__class__.__name__ if inst else None
        category = cat or cog_name or "Uncategorized"
        if category in categories and await vis.can_use(_help_command_key(cmd)):
            visible_categories.add(category)
    # Top-level command names: a group is suggested only when at least
    # one of its subcommands is visible to this user.
    cmd_names = []
    for cmd in ctx.bot.application_commands:
        if isinstance(cmd, discord.SlashCommandGroup):
            # any() cannot drive an async generator, so the check is a
            # plain loop with an early break.
            visible_sub = False
            for sub in _iter_runnable_commands(cmd.subcommands):
                if await vis.can_use(_help_command_key(sub)):
                    visible_sub = True
                    break
            if visible_sub:
                cmd_names.append(cmd.name)
        elif await vis.can_use(_help_command_key(cmd)):
            cmd_names.append(cmd.name)
    # Filter suggestions by substring match, limit to 25
    choices = [c for c in visible_categories if val in c.lower()]
    choices += [c for c in cmd_names if val in c.lower()]
    return choices[:25]




class Helpinfodoc(commands.Cog):
    def __init__(self, client):
        self.bot = client

    @staticmethod
    def build_tag_embed(view, tag, cmds):
        """Embed listing every command in one tag.

        Called by TagDropdown.callback as
        Helpinfodoc.build_tag_embed(self.view, tag, COMMAND_TAGS[tag]).
        It never existed, so picking a category in TagPageView would
        raise AttributeError the moment the pager is wired up.
        `view` is accepted for that call shape and unused -- the
        dropdown stays on the original message; this embed is the
        ephemeral reply. Lists are chunked with _chunk_lines so a big
        tag (Admin, 55+ commands) stays inside Discord's 1024-char
        field cap, and fields are capped at 25 fields / 5800 total
        chars with a "+N more" note if a tag ever overflows.
        """
        lines = [f"/{c}" for c in (cmds or [])] or ["(none)"]
        fields = _chunk_lines(tag.title(), lines)
        title = f"{tag.title()} Commands"
        description = f"{len(cmds or [])} command(s) in **{tag}**"
        embed = discord.Embed(
            title=title,
            description=description,
            color=discord.Color.blurple(),
        )
        # Cap BOTH field count (25) and embed total (5800): chunked
        # fields are each up to 1000 chars, so 24 of them would still
        # blow the 6000-char embed cap -- the same class of bug as the
        # /generate_tags 400. Stop packing when the next field would
        # push the total over, and note how many lines were left out.
        shown = []
        total = len(title) + len(description)
        for name, value in fields:
            cost = len(name) + len(value)
            if shown and (len(shown) >= MAX_FIELDS - 1 or total + cost > MAX_EMBED_TOTAL):
                break
            shown.append((name, value))
            total += cost
        for name, value in shown:
            embed.add_field(name=name, value=value, inline=False)
        if len(fields) > len(shown):
            remaining = sum(f[1].count("\n") + 1 for f in fields[len(shown):])
            embed.add_field(
                name="...and more",
                value=f"+{remaining} more command(s) in this tag.",
                inline=False,
            )
        return embed

