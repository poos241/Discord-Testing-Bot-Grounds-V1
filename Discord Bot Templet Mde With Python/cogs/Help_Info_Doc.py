def _iter_runnable_commands(commands):
    """Yield every runnable slash command, expanding groups into subcommands.

    pycord SlashCommandGroups (e.g. /ticket, /backup) have no .callback of
    their own -- only real commands do. Touching cmd.callback on a group
    raises AttributeError ('SlashCommandGroup' object has no attribute
    '_callback'), which is what crashed /help and /diagnose_docs.
    """
    for cmd in commands:
        if isinstance(cmd, discord.SlashCommandGroup):
            yield from _iter_runnable_commands(cmd.subcommands)
        else:
            yield cmd


def _cmd_cog(cmd):
    """The cog instance a command belongs to, or None.

    pycord sets .cog on commands added via a cog; the .callback function's
    __self__ is NOT set (the callback stays a plain function), so reading
    __self__ always returns None and every command would land in
    "Uncategorized". Uses .callback's __self__ only as a fallback.
    """
    cog = getattr(cmd, "cog", None)
    if cog is not None:
        return cog
    cb = getattr(cmd, "callback", None)
    return getattr(cb, "__self__", None) if cb is not None else None


# Discord embed limits: a field value holds at most 1024 chars, an embed
# at most 6000 chars total and 25 fields. Lists built from the live
# command set (150 runnable commands) blow past 1024 in a single field,
# and Discord rejects the whole reply with 400 Invalid Form Body -- which
# shows up as "The application did not respond". Everything below keeps
# every field and every embed inside those limits.
MAX_FIELD_VALUE = 1000
MAX_EMBED_TOTAL = 5800


def _truncate(text, limit=MAX_FIELD_VALUE):
    """Shorten one field value to fit Discord's 1024-char cap."""
    text = text or ""
    if len(text) <= limit:
        return text
    return text[:limit - 3] + "..."


def _chunk_lines(base_name, lines, max_value_len=MAX_FIELD_VALUE):
    """Split lines into (name, value) field pairs, each value in limits.

    Lines are packed whole, never split mid-line; a single over-long line
    is truncated. Continuation fields are named "Name (cont. 2)" etc.
    """
    fields = []
    current = []
    current_len = 0
    chunk_no = 1
    for line in lines:
        line = _truncate(line, max_value_len)
        add = len(line) + (1 if current else 0)  # +1 for the newline
        if current and current_len + add > max_value_len:
            name = base_name if chunk_no == 1 else f"{base_name} (cont. {chunk_no})"
            fields.append((name, "\n".join(current)))
            chunk_no += 1
            current = [line]
            current_len = len(line)
        else:
            current.append(line)
            current_len += add
    if current:
        name = base_name if chunk_no == 1 else f"{base_name} (cont. {chunk_no})"
        fields.append((name, "\n".join(current)))
    return fields


async def _send_chunked_embeds(ctx, title, color, fields, description=None):
    """Send fields across as many embeds as needed (<=25 fields, <=5800 chars each).

    First embed via ctx.respond, the rest via ctx.followup.send.
    """
    embeds = []
    cur_fields = []
    cur_total = len(title or "") + len(description or "")
    for name, value in fields:
        cost = len(name) + len(value)
        if cur_fields and (len(cur_fields) >= MAX_FIELDS or cur_total + cost > MAX_EMBED_TOTAL):
            embeds.append(cur_fields)
            cur_fields = []
            cur_total = len(title or "") + len(description or "")
        cur_fields.append((name, value))
        cur_total += cost
    if cur_fields:
        embeds.append(cur_fields)
    first = True
    for i, flds in enumerate(embeds):
        embed = discord.Embed(
            title=title if i == 0 else f"{title} (cont.)",
            description=description if i == 0 else None,
            color=color,
        )
        for name, value in flds:
            embed.add_field(name=name, value=value, inline=False)
        if first:
            await ctx.respond(embed=embed, ephemeral=True)
            first = False
        else:
            await ctx.followup.send(embed=embed, ephemeral=True)


